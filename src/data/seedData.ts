function formatRelativeDate(daysAgo: number, monthsAgo = 0): string {
  const now = new Date();
  const target = new Date(
    now.getFullYear(),
    now.getMonth() - monthsAgo,
    Math.max(1, now.getDate() - daysAgo),
  );
  const y = target.getFullYear();
  const m = String(target.getMonth() + 1).padStart(2, '0');
  const d = String(target.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

function formatMonthDay(dayOfMonth: number, monthsAgo = 0): string {
  const now = new Date();
  const maxDay = new Date(now.getFullYear(), now.getMonth() - monthsAgo + 1, 0).getDate();
  const clampedDay = Math.min(dayOfMonth, monthsAgo === 0 ? Math.max(1, now.getDate()) : maxDay);
  const target = new Date(now.getFullYear(), now.getMonth() - monthsAgo, clampedDay);
  const y = target.getFullYear();
  const m = String(target.getMonth() + 1).padStart(2, '0');
  const d = String(target.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

function formatFutureDate(monthsAhead: number): string {
  const now = new Date();
  const target = new Date(now.getFullYear(), now.getMonth() + monthsAhead, 15);
  const y = target.getFullYear();
  const m = String(target.getMonth() + 1).padStart(2, '0');
  const d = String(target.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

